let svg, g, zoom, projection;

async function initMap() {
  const container = document.getElementById('map-container');
  container.innerHTML = ''; // Clear container

  const width = container.clientWidth;
  const height = container.clientHeight;

  svg = d3.select('#map-container')
    .append('svg')
    .attr('width', '100%')
    .attr('height', '100%')
    .attr('viewBox', `0 0 ${width} ${height}`)
    .attr('preserveAspectRatio', 'xMidYMid meet');

  // Background water/map listener to close panel when clicking empty space
  svg.on('click', (event) => {
    if (event.target.tagName === 'svg' || event.target.id === 'map-container') {
      closeDetailPanel();
    }
  });

  g = svg.append('g');

  // Setup Zoom behaviour
  zoom = d3.zoom()
    .scaleExtent([1, 8])
    .on('zoom', (event) => {
      g.attr('transform', event.transform);
    });

  svg.call(zoom);

  try {
    const response = await fetch(geoUrl);
    const data = await response.json();

    // Map Projection fit to container size
    projection = d3.geoMercator().fitSize([width, height], data);
    const path = d3.geoPath().projection(projection);

    // Layer 1: Draw District Boundaries (Land) in their original exact locations
    g.selectAll('path.district')
      .data(data.features)
      .enter()
      .append('path')
      .attr('d', path)
      .attr('class', 'district')
      .attr('data-name', d => d.properties.name)
      .on('click', handleDistrictClick)
      .append('title')
      .text(d => d.properties.name);

    // Layer 6: Draw District Text Labels at the very top so they are never hidden by the river
    g.selectAll('text.district-label')
      .data(data.features)
      .enter()
      .append('text')
      .attr('class', 'district-label')
      .attr('transform', d => {
        let centroid = path.centroid(d);
        let tx = centroid[0];
        let ty = centroid[1];

        // Tweak Yeongdeungpo label to sit nicely on the mainland, away from Saetgang
        if (d.properties.name === "영등포구") {
          tx -= 5;
          ty += 15;
        }

        return `translate(${tx}, ${ty})`;
      })
      .attr('dy', '.35em')
      .text(d => d.properties.name);

    // Setup zoom controls wiring
    d3.select('#zoom-in').on('click', () => {
      svg.transition().duration(300).call(zoom.scaleBy, 1.4);
    });

    d3.select('#zoom-out').on('click', () => {
      svg.transition().duration(300).call(zoom.scaleBy, 0.7);
    });

    d3.select('#zoom-reset').on('click', () => {
      svg.transition().duration(500).call(zoom.transform, d3.zoomIdentity);
    });

  } catch (error) {
    console.error("지도를 로드하는 중 에러가 발생했습니다:", error);
    container.innerHTML = '<div style="color:#b89665; text-align:center; padding-top:20%;">서울 지도를 가져오는 중 에러가 발생했습니다. 네트워크 연결 상태를 확인해주세요.</div>';
  }
}

// Handler for district shape click
function handleDistrictClick(event, d) {
  event.stopPropagation();
  
  // Highlight active path
  d3.selectAll('.district').classed('active', false);
  d3.select(event.currentTarget).classed('active', true);

  const nameKor = d.properties.name;
  const data = districtData[nameKor] || getFallbackData(nameKor);

  openDetailPanel(data);
}

// Opens the right-side detail drawer and slides map left
function openDetailPanel(data) {
  const container = document.getElementById('app-container');
  
  // Fill sidebar data
  document.getElementById('detail-title').textContent = data.title + (data.engName ? ': ' + data.engName : '');
  document.getElementById('detail-description').textContent = data.description;
  document.getElementById('detail-image').src = data.image;

  // Render Landmark list dynamically inside sidebar
  const landmarkListContainer = document.getElementById('detail-landmark-list');
  landmarkListContainer.innerHTML = '';
  
  data.landmarks.forEach(lm => {
    const card = document.createElement('article');
    card.className = 'landmark-card';
    card.setAttribute('data-landmark-name', lm.name);

    // If this landmark is the representative one, add a badge
    if (lm.isRepresentative) {
      const badge = document.createElement('div');
      badge.className = 'rep-badge';
      badge.textContent = '대표 관광지';
      card.appendChild(badge);
    }

    // Content box
    const content = document.createElement('div');
    content.className = 'landmark-card-content';

    // Title
    const title = document.createElement('h4');
    title.className = 'landmark-card-title';
    title.textContent = lm.name;

    // Tags box
    const tagsBox = document.createElement('div');
    tagsBox.className = 'tags';
    lm.tags.forEach(tagText => {
      const span = document.createElement('span');
      span.className = 'tag';
      span.textContent = tagText;
      tagsBox.appendChild(span);
    });

    // Description
    const desc = document.createElement('p');
    desc.className = 'landmark-card-desc';
    desc.textContent = lm.desc;

    // Append all elements
    content.appendChild(title);
    content.appendChild(tagsBox);
    content.appendChild(desc);
    
    // Image for the landmark card (only if representative)
    if (lm.isRepresentative) {
      const img = document.createElement('img');
      img.className = 'landmark-card-image';
      img.src = lm.img;
      img.alt = lm.name + ' 이미지';
      card.appendChild(img);
      
      // Make it clickable
      card.style.cursor = 'pointer';
      card.addEventListener('click', () => {
        openLandmarkDetail(lm, data.title);
      });
    }
    
    card.appendChild(content);
    landmarkListContainer.appendChild(card);
  });

  // Show district view, hide landmark view
  document.getElementById('district-view').style.display = 'block';
  document.getElementById('landmark-view').style.display = 'none';

  // Activate sliding transitions
  container.classList.add('detail-active');
}


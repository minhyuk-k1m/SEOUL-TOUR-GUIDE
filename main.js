  const districtView = document.getElementById('district-view');
  const landmarkView = document.getElementById('landmark-view');
  
  districtView.style.display = 'none';
  landmarkView.style.display = 'block';
  
  // Populate data
  document.getElementById('landmark-detail-image').src = lm.img;
  document.getElementById('landmark-detail-title').textContent = lm.name;
  document.getElementById('landmark-detail-description').textContent = lm.detailDesc || lm.desc;
  
